import json
import numpy as np
from multiprocessing import cpu_count

def writeGeometryJSON(filename, scale, volP, surfP):
  """
  Writes a set of parameters for a geometry into a JSON file

  Inputs:
    filename - the JSON file to write to
    scale    - scale factor of the coordinates (1 for m, 1e-3 for mm, etc)
    volP     - dictionary of volume parameters containing:
      num      - number of volumes in the mesh
      vol0     - parameters for volume 0, including:
        epr          - relative permittivity of the volume
        mur          - relative permeability of the volume
        sigma        - conductivity of the volume
        tanD         - loss tangent of the volume
        saveFieldInt - boolean flag for whether to save the integral of the field in the volume
      vol1     - same as above for volume 1, repeat to num - 1 
    surfP    - dictionary of surface parameters containing:
      num      - number of surfaces in the mesh
      surf0    - parameters for surface 0, including:
        type     - categorization of each surface in the geometry (currently "PEC", "Outer", "Port", "Imp", or "Voltage")
        if type == "Port":
          portType  - The type of port (currently "R", "L", "C", or "Open")
          Z         - The resistance, inductance, or capacitance of the port (real-valued, not including contribution of frequency)
          width     - Width of the port (i.e.: length NOT in the integration direction)
          direction - Unit vector pointing in the integration direction of the port
          normal    - Direction normal to the port surface
          Vsmag     - Magnitude of the drive at this port
        elif type == "Imp":
          impType   - The circuit representation of the surface impedance ("R", "L", or "C")
          Z         - The resistance, inductance, or capacitance of the surface (real-valued, not including contribution of frequency)
          normal    - Direction normal to the surface
          epr       - Relative permittivity of the volume the surface lies in
        elif type == "Voltage":
          V         - The voltage to enforce across the port surface (currently only supported for simType "E" and "Phi")
          direction - Unit vector pointing from signal to GND
          width     - Width of the surface (i.e.: length NOT in the integration direction)
        elif type == "Output":
          fieldType - The type of field to calculate ("E", "H", "A", "Phi", or "surfPart" for surface participation)
          direction - Unit vector pointing in the integration direction of the field
          if fieldType == "surfPart":
            thickness - thickness of the interface layer
            normal    - unit vector normal to the surface being integrated over (pointing in the direction of the interface layer)
            epr       - relative permittivity of the interface layer
      surf1    - same as above, repeat to num-1
    lineP    - dictionary of line parameters containing:
      num      - number of unique lines in the mesh
      line0    - parameters for line 0, including:
        type - categorization of the line (currently only "singLine")
        if type == "singLine":
          
      line1    - same as above, repeat to num-1

  """
  data = {}
  data["scale"] = scale
  data["volP"] = volP
  data["surfP"] = surfP
  with open(filename, 'w', encoding='utf-8') as f:
    json.dump(data, f, ensure_ascii=False, indent=2)

def writeSimJSON(filename, simType, probP, solveP, outP, numProcs=-1):
  """
  Writes a set of parameters for a simulation into a JSON file

  Inputs:
    probP     - Parameters of the problem
      type      - Type of problem to solve ("FD", "TD", "Eig")
      geomFile  - Path to the geometry JSON file (generated by writeGeometryJSON())
      if type == "FD":
        minFreq   - Lowest frequency to solve the problem at (in Hz)
        maxFreq   - Highest frequency to solve the problem at (in Hz)
        freqStep  - Spacing between frequency points (in Hz)
        numSteps  - Number of frequency points (alternative to freqStep)
        stepType  - If "numSteps" is used, the type of steps to take (either "linear" or "log")
      if type == "TD":
        dt        - Timestep size (in s)
        totT      - Total time to run the simulation for (in s)
        beta      - Newmark-beta constant for time-marching (0.0 to 1.0)
        driveP    - Parameters of the drive
          type      - Type of pulse to use ("Sine", "Gaussian")
          freq      - Center frequency of the drive (in Hz)
          t_off     - Offset time for the center of the pulse envelope (in s)
          sigma     - Rise time of the gaussian edges of the envelope (in s)
      if type == "Eig":
        numEig     - The number of eigenvalues to solve for
      bOrder     - Order for basis functions
      sOrder     - Order for singular basis functions (if used)
      portMatrix - Compute full port impedance matrix (by driving from all ports)
    solveP     - Parameters of the solver
      pkg        - The solver package to use ("SciPy", "PETSc", "SLEPc")
      if type == "Eig":
        shift      - Center frequency for shift-invert (or None) 
    outP        - Parameters of the outputs
      if type == "FD" or "TD":
        saveV       - Whether to save the input / output voltages
        saveS       - Whether to save the S-parameters
      resFile     - Filename to save results into (voltages, S-parameters, eigenpairs, etc)
      saveFields  - Whether to save the fields 
      if saveFields:
        fieldType   - Indicates if the saved quantity should be the total field magnitude ("Mag") or the vector field ("Vec")
        fFile       - Filename to save fields (.npy format)
        if type == "TD":
          saveSteps   - Timesteps to save the field at
          saveEle     - Element numbers to save the field for (can be set to "all")
      fieldPoints - Points to evaluate the field at. Can be provided as a list of points or 
                    as a path to a .csv file containing those points. Defaults to []
      
    numProcs  - Number of processors available. Can be ommitted to automatically use all processes
  """
  data = {}
  data["probP"] = probP
  data["solveP"] = solveP
  data["outP"] = outP
  if numProcs != -1:
    data["numProcs"] = numProcs
  with open(filename, 'w', encoding='utf-8') as f:
    json.dump(data, f, ensure_ascii=False, indent=2)

def readGeometryJSON(filename, volStartInds, volEleTypes, triList, surfStartInds, \
                     lineList, lineStartInds, nodesetList, nodesetStartInds, outerBC):
  """
  Reads a set of parameters for a geometry from a JSON file and parses
  them into a format used by the remaining FEM code

  Inputs:
    filename         - Name of the JSON file
    volStartInds     - Element index where each volume starts
    volEleTypes      - Element type for each volume
    triList          - List of nodes associated with each triangle
    surfStartInds    - Element index where each surface starts
    lineList         - List of nodes associated with each edge in a line
    lineStartInds    - Element index where each new line block starts
    nodesetList      - List of nodes in nodesets
    nodesetStartInds - Element index where each new nodeset starts
    outerBC          - Boundary condition for the outer boundary
  Outputs:
    tetVolP       - Parameters of the volumes discretized with tets
    wedgeVolP     - Parameters of the volumes discretized with wedges
    portList      - List of nodes forming triangles on each port surface
    portP         - Parameters of the port surfaces
    portList      - List of nodes forming triangles on each qubit surface
    portP         - Parameters of the qubit surfaces
    impList       - List of nodes forming triangles on each impedance surface
    impP          - Parameters of the impedance surfaces
    voltList      - List of nodes forming triangles on each voltage surface
    voltP         - Parameters of the voltage surfaces
    outList       - List of nodes forming triangles on each output surface
    outP          - Parameters of the output surfaces
    pecList       - List of nodes forming triangles on each PEC surface
    pecStartInds  - Marks the row where each new PEC starts in 'pecList'
    abcList       - List of nodes forming triangles on the ABC surface
    singEdgeList  - List of nodes forming each singular edge
    scale         - Scale factor for the coordinates
  """
  with open(filename, 'r') as openfile:
    data = json.load(openfile)

  ## Split the volume parameters by element type and 
  # add information on which row they start at
  volP = data["volP"]
  tetVolP = {} # Isolate parameters for volumes containing tets
  wedgeVolP = {} # Isolate parameters for volumes containing wedges
  tetInd = 0
  wedgeInd = 0
  for ii in range(volP["num"]):
    if volEleTypes[ii].lower() == "tet" or volEleTypes[ii].lower() == "tetra":
      tetVolP[f"vol{tetInd}"] = volP[f"vol{ii}"]
      for prop in ["epr", "mur", "tanD", "sigma"]: # Set up material properties to support anisotropy
        tetVolP[f"vol{tetInd}"][prop] = np.array(tetVolP[f"vol{tetInd}"][prop], dtype=np.float64)
        if tetVolP[f"vol{tetInd}"][prop].size == 1: # If the material is isotropic, represent it in anisotropic form
          tetVolP[f"vol{tetInd}"][prop] = tetVolP[f"vol{tetInd}"][prop]*np.eye(3, dtype=np.float64)
      tetVolP[f"vol{tetInd}"]["murInv"] = np.linalg.inv(tetVolP[f"vol{tetInd}"]["mur"])
      tetVolP[f"vol{tetInd}"]["startInd"] = volStartInds[ii]
      tetInd += 1
    elif volEleTypes[ii] == "Wedge":
      wedgeVolP[f"vol{wedgeInd}"] = volP[f"vol{ii}"]
      for prop in ["epr", "mur", "tanD", "sigma"]: # Set up material properties to support anisotropy
        wedgeVolP[f"vol{wedgeInd}"][prop] = np.array(wedgeVolP[f"vol{wedgeInd}"][prop], dtype=np.float64)
        if wedgeVolP[f"vol{wedgeInd}"][prop].size == 1: # If the material is isotropic, represent it in anisotropic form
          wedgeVolP[f"vol{wedgeInd}"][prop] = wedgeVolP[f"vol{wedgeInd}"][prop]*np.eye(3, dtype=np.float64)
      wedgeVolP[f"vol{wedgeInd}"]["murInv"] = np.linalg.inv(wedgeVolP[f"vol{wedgeInd}"]["mur"])
      wedgeVolP[f"vol{wedgeInd}"]["startInd"] = volStartInds[ii]
      wedgeInd += 1
  tetVolP["num"] = tetInd
  wedgeVolP["num"] = wedgeInd
  
  ## Split the surface list and parameters by surface type 
  surfP = data["surfP"]
  portP = {} # Port surfaces
  portList = np.zeros((0,3), dtype=triList.dtype) 
  portInd = 0
  qubitP = {} # Qubit surfaces
  qubitList = np.zeros((0,3), dtype=triList.dtype) 
  qubitInd = 0
  impP = {} # Impedance surfaces
  impList = np.zeros((0,3), dtype=triList.dtype) 
  impInd = 0
  voltP = {} # Voltage surfaces
  voltList = np.zeros((0,3), dtype=triList.dtype) 
  voltInd = 0
  outP = {} # Output surfaces for field calculations
  outList = np.zeros((0,3), dtype=triList.dtype) 
  outInd = 0
  pecList = np.zeros((0,3), dtype=triList.dtype) # PEC surfaces
  pecStartInds = [] 
  maxPECLen = 0 # Track the largest PEC surface to treat it as GND
  abcList = np.zeros((0,3), dtype=triList.dtype) # ABC surface
  
  surfStartInds.append(len(triList)) # Add the length of the list to ensure the last addition functions correctly
  for ii in range(surfP["num"]):
    match surfP[f"surf{ii}"]["type"]:
      case "Port":
        portP[f"{portInd}"] = surfP[f"surf{ii}"]
        portP[f"{portInd}"]["type"] = surfP[f"surf{ii}"]["portType"]
        portP[f"{portInd}"]["startInd"] = len(portList)
        portList = np.append(portList, triList[surfStartInds[ii]:surfStartInds[ii+1]], axis=0)
        portInd += 1
      case "Qubit":
        qubitP[f"{qubitInd}"] = surfP[f"surf{ii}"]
        qubitP[f"{qubitInd}"]["startInd"] = len(qubitList)
        qubitList = np.append(qubitList, triList[surfStartInds[ii]:surfStartInds[ii+1]], axis=0)
        qubitInd += 1
      case "Imp":
        impP[f"{impInd}"] = surfP[f"surf{ii}"]
        impP[f"{impInd}"]["type"] = surfP[f"surf{ii}"]["impType"]
        impP[f"{impInd}"]["startInd"] = len(impList)
        impList = np.append(impList, triList[surfStartInds[ii]:surfStartInds[ii+1]], axis=0)
        impInd += 1
      case "Voltage":
        voltP[f"{voltInd}"] = surfP[f"surf{ii}"]
        voltP[f"{voltInd}"]["startInd"] = len(voltList)
        voltList = np.append(voltList, triList[surfStartInds[ii]:surfStartInds[ii+1]], axis=0)
        voltInd += 1
      case "PEC":
        surfLen = surfStartInds[ii+1] - surfStartInds[ii]
        if surfLen > maxPECLen: # If this is the largest PEC thus far, set it as GND
            maxPECLen = surfLen
            pecStartInds = [pecStartInds[ii] + surfLen for ii in range(len(pecStartInds))]
            pecStartInds.insert(0, 0)
            pecList = np.append(triList[surfStartInds[ii]:surfStartInds[ii+1]], pecList, axis=0)
        else:
          pecStartInds.append(len(pecList))
          pecList = np.append(pecList, triList[surfStartInds[ii]:surfStartInds[ii+1]], axis=0)
      case "Outer":
        if outerBC == "PEC":
          surfLen = surfStartInds[ii+1] - surfStartInds[ii]
          if surfLen > maxPECLen: # If this is the largest PEC thus far, set it as GND
            maxPECLen = surfLen
            pecStartInds = [pecStartInds[ii] + surfLen for ii in range(len(pecStartInds))]
            pecStartInds.insert(0, 0)
            pecList = np.append(triList[surfStartInds[ii]:surfStartInds[ii+1]], pecList, axis=0)
          else:
            pecStartInds.append(len(pecList))
            pecList = np.append(pecList, triList[surfStartInds[ii]:surfStartInds[ii+1]], axis=0)
        elif outerBC == "ABC":
          abcList = np.append(abcList, triList[surfStartInds[ii]:surfStartInds[ii+1]], axis=0)
      case "Output":
        outP[f"{outInd}"] = surfP[f"surf{ii}"]
        outP[f"{outInd}"]["type"] = surfP[f"surf{ii}"]["fieldType"]
        outP[f"{outInd}"]["startInd"] = len(outList)
        outList = np.append(outList, triList[surfStartInds[ii]:surfStartInds[ii+1]], axis=0)
        outInd += 1
  pecStartInds.append(len(pecList))
  portP["num"] = portInd
  qubitP["num"] = qubitInd
  impP["num"] = impInd
  voltP["num"] = voltInd
  outP["num"] = outInd

  singEdgeList = np.zeros((0,2), dtype=np.int32)
  singEdgeP = {} # Singular edges
  singEdgeInd = 0
  lineStartInds.append(len(lineList))
  if "lineP" in data:
    lineP = data["lineP"]
    for ii in range(lineP["num"]):
      match lineP[f"line{ii}"]["type"]:
        case "singLine": # Singular lines
          singEdgeP[f"{singEdgeInd}"] = lineP[f"line{ii}"]
          if "coeff" not in lineP[f"line{ii}"]:
            # If a singular coefficient isn't provided, assume it's 2/3 (based on J. D. Jackson formula)
            singEdgeP[f"{singEdgeInd}"]["coeff"] = 2/3 
          singEdgeP[f"{singEdgeInd}"]["startInd"] = len(singEdgeList)
          singEdgeInd += 1
          singEdgeList = np.append(singEdgeList, lineList[lineStartInds[ii]:lineStartInds[ii+1]], axis=0)
  singEdgeP["num"] = singEdgeInd

  singVertList = np.zeros((0,), dtype=nodesetList.dtype)
  singVertP = {}
  singVertInd = 0
  nodesetStartInds.append(len(nodesetList))
  if "nodesetP" in data:
    nodesetP = data["nodesetP"]
    for ii in range(nodesetP["num"]):
      match nodesetP[f"nodeset{ii}"]["type"]:
        case "singVert": # Singular vertices
          singVertP[f"{singVertInd}"] = nodesetP[f"nodeset{ii}"]
          if "coeff" not in nodesetP[f"nodeset{ii}"]:
            # If a singular coefficient isn't provided, assume it's 0.463 (based on J. D. Jackson formula for corners)
            singVertP[f"{singVertInd}"]["coeff"] = 0.463 
          singVertP[f"{singVertInd}"]["startInd"] = len(singVertList)
          singVertInd += 1
          singVertList = np.append(singVertList, nodesetList[nodesetStartInds[ii]:nodesetStartInds[ii+1]], axis=0)
  singVertP["num"] = singVertInd

  return tetVolP, wedgeVolP, portList, portP, qubitList, qubitP, impList, impP, voltList, voltP, \
         pecList, pecStartInds, abcList, outList, outP, singEdgeList, singEdgeP, singVertList, singVertP, data["scale"]

def readSimJSON(filename):
  """
  Reads a set of simulation parameters from a JSON file and parses them into a format
  used by the remainder of the FEM code
  """

  with open(filename, 'r') as openfile:
    data = json.load(openfile)

  ## For options that are not yet fully implemented, set them automatically
  data["simType"] = "E" # Always run field-based simulations
  data["probP"]["outBC"] = "PEC" # Force the simulation to use PEC on the outer boundary
  data["probP"]["maxAMR"] = 1 # Don't perform adaptive refinement
  data["probP"]["singEdgeFlag"] = True # Always use singular edge functions (if singular basis functions are used in general)
  data["probP"]["3DIntOrder"] = 2*data["probP"]["bOrder"] # Set gaussian quadrature order to be twice that of the basis functions for exact integration
  data["probP"]["2DIntOrder"] = 2*data["probP"]["bOrder"] # Set gaussian quadrature order for 2D integrals to be that of the basis functions for exact integration
  data["probP"]["numSubDs"] = 1 # Don't use domain decomposition
  data["probP"]["bOrder_long"] = 1 # If wedges/prisms are included, only use 1st order longitudinal functions
  data["probP"]["sOrder_long"] = 1 # If wedges/prisms are included, only use 1st order longitudinal functions

  data["solveP"]["ksp"] = "LU" # Force use of a direct solver
  data["solveP"]["pc"] = "LU" # Force use of a direct solver
  data["solveP"]["preType"] = "Dynamic" # Preconditioner type is arbitrary since direct solver is used
  if data["solveP"]["pkg"].lower() == "scipy":
    data["solveP"]["pkg"] = "SciPy" # Correct for capitalization
  elif data["solveP"]["pkg"].lower() == "petsc":
    data["solveP"]["pkg"] = "PETSc" # Correct for capitalization
  elif data["solveP"]["pkg"].lower() == "slepc":
    data["solveP"]["pkg"] = "SLEPc" # Correct for capitalization
  data["solveP"]["maxit"] = 1 # Needed for residual saving

  if "numProcs" in data:
    numProcs = data["numProcs"]
  else:
    numProcs = cpu_count() # If a processor number is not provided, use all available CPUs

  if "portMatrix" not in data["probP"]:
    data["probP"]["portMatrix"] = False

  if "sOrder" not in data["probP"]:
    # If a singular basis function order isn't provided seperately, assume it's the same as the regular order
    data["probP"]["sOrder"] = data["probP"]["bOrder"]
  
  if data["probP"]["type"] == "FD": # For FD simulations, form the frequency vector
    if "numSteps" in data["probP"]:
      if data["probP"]["stepType"] == "linear":
        data["probP"]["freqs"] = np.linspace(data["probP"]["minFreq"], data["probP"]["maxFreq"], data["probP"]["numSteps"])
      elif data["probP"]["stepType"] == "log":
        data["probP"]["freqs"] = np.logspace(np.log10(data["probP"]["minFreq"]), np.log10(data["probP"]["maxFreq"]), data["probP"]["numSteps"])
    if "freqStep" in data["probP"]:
      if data["probP"]["freqStep"] != 0: # Multiple frequencies
        data["probP"]["freqs"] = np.arange(data["probP"]["minFreq"], data["probP"]["maxFreq"]+data["probP"]["freqStep"], data["probP"]["freqStep"])
      else: # Single frequency
        data["probP"]["freqs"] = np.array([data["probP"]["minFreq"]])

  # TODO: Maybe remove time domain sims?
  elif data["probP"]["type"] == "TD": # For TD simulations, form the drive and time vectors
    data["probP"]["t"] = np.arange(0, data["probP"]["totT"], data["probP"]["dt"])
    data["probP"]["numT"] = len(data["probP"]["t"])
    match data["probP"]["driveP"]["type"]:
      case "Gaussian": 
        data["probP"]["driveP"]["Vs"] = np.exp(-(data["probP"]["t"]-data["probP"]["driveP"]["t_off"])**2/(2*data["probP"]["driveP"]["sigma"]**2)) \
                                          * np.sin(2*np.pi*data["probP"]["driveP"]["freq"]*data["probP"]["t"])
      case "Sine":
        data["probP"]["driveP"]["Vs"] = np.sin(2*np.pi*data["probP"]["driveP"]["freq"]*data["probP"]["t"])

  if "adaptSweep" not in data["solveP"]: # If adaptive sweep settings aren't specified, assume it's enabled
    data["solveP"]["adaptSweep"] = True

  if "saveInfo" not in data["solveP"]: # If not specified to save diagnostic info, don't save
    data["solveP"]["saveInfo"] = False

  if "saveFields" not in data["outP"]: # If not specified whether to save field info, don't
    data["outP"]["saveFields"] = False

  # If points to evaluate the field at are provided, process them
  if "fieldPoints" in data["outP"]:
    if type(data["outP"]["fieldPoints"]) is list:
      data["outP"]["fieldPoints"] = np.array(data["outP"]["fieldPoints"])
    elif type(data["outP"]["fieldPoints"]) is str:
      if data["outP"]["fieldPoints"][-4:] == ".npy":
        data["outP"]["fieldPoints"] = np.load(data["outP"]["fieldPoints"])
      else:
        assert False, "fieldPoints data must be provided as a list of points in the .json file directly or as a .npy file"
  else:
    data["outP"]["fieldPoints"] = []

  return data["simType"], data["probP"], data["solveP"], data["outP"], numProcs